# ---------------------------------------------------------------- group side


def unit_group(M: int) -> list[int]:
    return [a for a in range(1, M) if math.gcd(a, M) == 1]


def closure(gens, M: int) -> set[int]:
    """Subgroup of (Z/M)^* generated by gens (multiplicative closure)."""
    H = {1}
    queue = [1]
    gs = sorted({g % M for g in gens if math.gcd(g, M) == 1})
    while queue:
        h = queue.pop()
        for g in gs:
            x = (h * g) % M
            if x not in H:
                H.add(x)
                queue.append(x)
    return H


def mult_order(p: int, M: int) -> int:
    d, x = 1, p % M
    while x != 1:
        x = (x * p) % M
        d += 1
    return d


def organ_A_curve(M: int, primes: list[int]):
    """Ghost-component count g(m) = [(Z/M)^*:H_m] as the prime set grows."""
    phiM = len(unit_group(M))
    H: set[int] = {1}
    curve = []
    m_star = None
    for m, q in enumerate(primes, start=1):
        if math.gcd(q, M) == 1 and (q % M) not in H:
            H = closure(H | {q % M}, M)
        idx = phiM // len(H)
        curve.append(idx)
        if m_star is None and idx == 1:
            m_star = m
    return np.array(curve, dtype=int), m_star


# ----------------------------------------------------------------- pole side


def ghost_diameter_stream(M: int, primes, beta: float, checkpoints):
    """
    Stream primes into the geometric-orbit convolution on (Z/M)^* and record
    the within-coset ghost diameter u = TV(nu, uniform on H) at checkpoints.

    w_p(p^j mod M) = (1 - p^{-beta}) p^{-j beta} summed over j >= 0; with
    d = ord_M(p) this is a closed form per orbit residue:
        w_p(p^{j0} mod M) = (1 - p^{-beta}) p^{-j0 beta} / (1 - p^{-d beta}).
    """
    units = unit_group(M)
    pos = {a: i for i, a in enumerate(units)}
    n = len(units)
    # permutation tables: row r sends entry i to the index of units[r]^{-1} * units[i],
    # so new[i] = sum_r w(r) nu[perm[r, i]] is the law of the product X * R
    perm = np.zeros((n, n), dtype=int)
    for r, ur in enumerate(units):
        ur_inv = pow(ur, -1, M)
        for i, a in enumerate(units):
            perm[r, i] = pos[(ur_inv * a) % M]

    nu = np.zeros(n)
    nu[pos[1]] = 1.0
    H: set[int] = {1}

    results = []  # (m, p_m, |H|, u)
    cps = set(checkpoints)
    m = 0
    p_last = 2
    for p in primes:
        m += 1
        p_last = p
        if math.gcd(p, M) == 1:
            if (p % M) not in H:
                H = closure(H | {p % M}, M)
            d = mult_order(p, M)
            x = p ** (-beta)
            norm = (1.0 - x) / (1.0 - x**d)
            new = np.zeros(n)
            pj = 1
            w = norm
            for _ in range(d):
                new += w * nu[perm[pos[pj]]]
                pj = (pj * p) % M
                w *= x
            nu = new
        if m in cps:
            hsize = len(H)
            uniform = 1.0 / hsize
            u = 0.5 * sum(
                abs(nu[pos[a]] - (uniform if a in H else 0.0)) for a in units
            )
            results.append((m, p_last, hsize, u))
    return results


def atom_budget(primes, betas, checkpoints):
    """A(beta, m) = prod_{p <= p_m} (1 - p^{-beta}), exact running product."""
    logs = {b: 0.0 for b in betas}
    out = {b: [] for b in betas}
    cps = set(checkpoints)
    m = 0
    for p in primes:
        m += 1
        for b in betas:
            logs[b] += math.log1p(-(p ** (-b)))
        if m in cps:
            for b in betas:
                out[b].append((m, p, math.exp(logs[b])))
    return out


