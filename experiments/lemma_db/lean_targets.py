PIPE_SENTINEL = "\x00ESCPIPE\x00"


def _clean(text: str, limit: int = 300) -> str:
    """One-line statement: strip markdown bold, dashes policy, collapse space."""
    t = text.replace("**", "").replace("\u2014", "-").replace("\u2013", "-")
    t = re.sub(r"\s+", " ", t).strip()
    if len(t) > limit:
        cut = t[:limit].rsplit(" ", 1)[0]
        t = cut + " ..."
    return t


def parse_readme_table(text: str) -> list[dict]:
    """Extract (id, module, description) rows from the VERIFIER table(s)."""
    rows = []
    for line in text.splitlines():
        s = line.strip()
        if not s.startswith("|") or not s.endswith("|"):
            continue
        cells = s.replace(r"\|", PIPE_SENTINEL).split("|")
        # cells[0] and cells[-1] are empty (leading/trailing pipe)
        if len(cells) < 4:
            continue
        tid = cells[1].replace(PIPE_SENTINEL, "|").strip()
        module = cells[2].replace(PIPE_SENTINEL, "|").strip()
        desc = "|".join(c.replace(PIPE_SENTINEL, "|") for c in cells[3:-1]).strip()
        if not tid or tid == "ID" or set(tid) <= {"-", ":", " "}:
            continue
        # keep only target rows: ids like #XX-1, #S-1..#S-3, V1..V4, #119/R3.5
        if not re.match(r"^(#|V\d)", tid):
            continue
        rows.append({"id": tid, "module": module, "desc": desc})
    return rows


def classify_readme_status(desc: str) -> str:
    """Status from the row text. Order matters; see docstring for the codes."""
    if re.search(r"BLOCKED-ON-MATHLIB|\bPARTIAL\b", desc):
        return "OPEN"
    if re.search(r"\bOPEN\b", desc):
        return "OPEN"
    if re.search(r"\bSorry\b|, sorry\)", desc):
        return "OPEN"
    if re.search(r"PROVED \((?:no )?sorry", desc) or re.search(
            r"DISCHARGED|CLOSED \(upstream\)|sorry-free|SORRY-FREE", desc):
        return "DISCHARGED"
    return "OPEN"


def parse_dossier_targets(path: Path, prefix: str) -> list[dict]:
    """Numbered items under '## Verification targets' headings."""
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()
    items: list[str] = []
    in_section = False
    current: list[str] | None = None
    for line in lines:
        if re.match(r"^##\s+Verification targets", line):
            in_section = True
            continue
        if in_section and re.match(r"^##?#?\s*#*\s*\S", line) and line.startswith("## "):
            break
        if not in_section:
            continue
        m = re.match(r"^(\d+)\.\s+(.*)$", line)
        if m:
            if current is not None:
                items.append(" ".join(current))
            current = [m.group(2)]
        elif current is not None and line.strip():
            current.append(line.strip())
        elif current is not None and not line.strip():
            # blank line inside the list is fine; keep collecting
            continue
    if current is not None:
        items.append(" ".join(current))
    out = []
    for k, item in enumerate(items, start=1):
        out.append({"id": f"{prefix}-{k}", "statement": _clean(item)})
    return out


