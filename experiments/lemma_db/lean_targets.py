def _finish(entry: dict) -> dict:
    """Merge triage data into a bare entry; enforce the schema."""
    tri = TRIAGE.get(entry["id"])
    if tri is None:
        tri = DEFAULT_DONE if entry["status"] == "DISCHARGED" else DEFAULT_OPEN
    entry["status"] = tri.get("status", entry["status"])
    entry["feasibility"] = tri["feasibility"]
    entry["value"] = tri["value"]
    entry["feasibility_why"] = tri["why"]
    entry["mathlib_routes"] = list(tri["mathlib_routes"])
    if "lean_ref" in tri:
        entry["lean_ref"] = tri["lean_ref"]
    if entry["status"] == "DRAFTED":
        entry["notes"] = ("Statement draft with sorry body in "
                          "lean/ZetaRH/VerifierQueue.lean; UNVERIFIED on this "
                          "box (no toolchain); not wired into ZetaRH.lean.")
    else:
        entry.setdefault("notes", "")
    assert entry["status"] in ALLOWED_STATUSES, entry
    return entry


def build_registry() -> dict:
    targets: list[dict] = []
    for row in parse_readme_table(README.read_text(encoding="utf-8")):
        entry = {
            "id": row["id"],
            "statement": _clean(row["desc"]),
            "source": "lean/README.md (" + row["module"] + ")",
            "status": classify_readme_status(row["desc"]),
        }
        targets.append(_finish(entry))
    for path, prefix, rel in DOSSIER_SOURCES:
        for item in parse_dossier_targets(path, prefix):
            entry = {
                "id": item["id"],
                "statement": item["statement"],
                "source": rel,
                "status": "OPEN",
            }
            targets.append(_finish(entry))
    return {
        "generated_by": "experiments/lemma_db/lean_targets.py",
        "sources": ["lean/README.md"] + [rel for _, _, rel in DOSSIER_SOURCES],
        "status_codes": sorted(ALLOWED_STATUSES),
        "feasibility_codes": FEASIBILITY_ORDER,
        "targets": targets,
    }


def write_registry(registry: dict | None = None, path: Path = REGISTRY_PATH) -> dict:
    registry = registry or build_registry()
    path.write_text(json.dumps(registry, indent=1, ensure_ascii=False) + "\n",
                    encoding="utf-8")
    return registry


def sort_key(entry: dict):
    return (FEASIBILITY_ORDER.index(entry["feasibility"]),
            VALUE_ORDER.index(entry["value"]),
            entry["id"])


def main() -> None:
    registry = write_registry()
    targets = sorted(registry["targets"], key=sort_key)
    counts: dict[str, int] = {}
    for t in registry["targets"]:
        counts[t["status"]] = counts.get(t["status"], 0) + 1
    print(f"registry written: {REGISTRY_PATH.relative_to(REPO_ROOT)}")
    print("status counts: " + ", ".join(
        f"{k}={counts.get(k, 0)}" for k in ["OPEN", "DRAFTED", "DISCHARGED", "UNVERIFIED"]))
    print()
    hdr = f"{'id':<14} {'status':<11} {'feas':<16} {'val':<5} statement"
    print(hdr)
    print("-" * len(hdr))
    for t in targets:
        if t["status"] == "DISCHARGED" and t["feasibility"] == "DONE":
            continue
        stmt = t["statement"][:70]
        print(f"{t['id']:<14} {t['status']:<11} {t['feasibility']:<16} "
              f"{t['value']:<5} {stmt}")
    ndone = sum(1 for t in registry["targets"]
                if t["status"] == "DISCHARGED" and t["feasibility"] == "DONE")
    print(f"\n(+ {ndone} DISCHARGED rows kept for the record, omitted above)")


if __name__ == "__main__":
    main()
